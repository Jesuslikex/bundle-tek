export function quoteCatalog(chain: string, venue: string) {
  const addresses = VENUES[chain + '/' + venue];
  const assets: QuoteAsset[] = [];
  const unresolved: string[] = [];
  for (const address of addresses ?? []) {
    const token = ASSETS[chain]?.[address];
    if (token) assets.push({ address, ...token });
    else unresolved.push(address);
  }
  // Keep the first asset stable: the chain/venue selector uses it as its default.
  const orderedAssets =
    chain === 'Solana' && venue === 'StonkFun' && assets.length > 1
      ? [
          assets[0],
          ...assets
            .slice(1)
            .filter((a) => FEATURED_STOCK_QUOTE_MINTS.has(a.address)),
          ...assets
            .slice(1)
            .filter((a) => !FEATURED_STOCK_QUOTE_MINTS.has(a.address)),
        ]
      : assets;
  return {
    captured: addresses !== undefined,
    assets: orderedAssets,
    unresolved,
  };
}
export function quoteAsset(chain: string, venue: string, address: string) {
  return quoteCatalog(chain, venue).assets.find((a) =>
    chain === 'Solana'
      ? a.address === address
      : a.address.toLowerCase() === address.toLowerCase(),
  );
}
export function validateQuoteSelection(plan: LaunchPlanInput) {
  const catalog = quoteCatalog(plan.chain, plan.launchpad);
  if (!catalog.captured) {
    if (plan.quoteAddress)
      throw new Error('No captured quote-token profile for this launchpad.');
    return;
  }
  const matches = catalog.assets.filter((a) => a.symbol === plan.currency);
  if (!matches.length)
    throw new Error(
      'Quote currency is not supported by this launchpad catalog.',
    );
  if (plan.quoteAddress) {
    const asset = quoteAsset(plan.chain, plan.launchpad, plan.quoteAddress);
    if (!asset || asset.symbol !== plan.currency)
      throw new Error(
        'Quote token address does not match the launchpad and symbol.',
      );
  } else if (matches.length > 1)
    throw new Error(
      'This symbol identifies multiple quote tokens. Select an exact token address.',
    );
}

export function chainQuoteAssets(chain: string): QuoteAsset[] {
  return Object.entries(ASSETS[chain] ?? {}).map(([address, asset]) => ({
    address,
    ...asset,
  }));
}
